"""Render RESULTS.md strictly from the measured results dict. No prose is invented."""

from __future__ import annotations

import json
from typing import Any

from cdebt.backtest.analysis import verdict_delta, verdict_ratio


def _f(x: float, d: int = 3) -> str:
    return "n/a" if x != x else f"{x:.{d}f}"


def _ci(c: list[float], d: int = 3) -> str:
    return f"[{_f(c[0], d)}, {_f(c[1], d)}]"


def _rate(r: dict[str, Any]) -> str:
    return f"{r['k']}/{r['n']} = {_f(r['rate'], 4)} (Wilson 95% {_ci(r['ci95'], 4)})"


MIN_EVENTS = 10


def _verdict(r: dict[str, Any], devs: list[str], name: str) -> str:
    events = r["exposed"]["k"] + r["unexposed"]["k"]
    if events < MIN_EVENTS:
        devs.append(
            f"{name}: only {events} outcome events in the contrast groups, so the "
            f"mechanical verdict was replaced by 'inconclusive (<{MIN_EVENTS} events)'. "
            "This rule was added AFTER seeing the results (post-hoc)."
        )
        return f"inconclusive (<{MIN_EVENTS} events)"
    return verdict_ratio(r["ci95"], r["rr_mh"])


def render(res: dict[str, Any], manifest: dict[str, Any] | None, command: str) -> str:
    d = res["descriptive"]
    L = [
        "# Backtest results (as measured)",
        "",
        "Generated by `" + command + "`. Definitions and hypotheses were frozen in "
        "`docs/METHOD.md` (pre-registration) before this run. Numbers below are copied from "
        "`RESULTS.json`; nothing is hand-edited.",
        "",
    ]
    if manifest:
        L += [
            f"- Dataset: `{manifest['dataset']}` revision `{manifest['revision']}`, fetched "
            f"{manifest['fetched_at']}"
        ]
    L += [
        f"- Merged PRs: {d['merged_prs']:,}; (PR, file) units: {d['units']:,}; eligible "
        f"(>=90d follow-up): {d['eligible_units']:,} in {d['eligible_repos']:,} repos",
        f"- Seed {res['seed']}, bootstrap replicates {res['reps']} (resampling repos)",
        "",
        "## Scope of this test (read first)",
        "",
        "Tests the **proxy** `S = (1-U)(1+C)` only. `ai_share` is constant (all PRs are "
        "agent-authored) and `blast_radius` is not tested. Outcomes are observable only when "
        "the follow-up is itself an agent PR in the curated set, so counts are undercounted "
        "and repo-activity confounded (analysis is stratified by repo). The quiz itself is "
        "not evaluated. Association only; no causal claim.",
        "",
        "## Descriptives",
        "",
        "| outcome (eligible units) | rate |",
        "|---|---|",
    ]
    for k, r in d["base_rates_eligible"].items():
        L.append(f"| {k} | {_rate(r)} |")
    L += [
        "",
        f"U levels (eligible units): {json.dumps(d['U_levels'])}",
        "",
        f"Agents (eligible units): {json.dumps(d['agents'])}",
        "",
    ]
    if "error" in res:
        return "\n".join(L + [f"**Analysis not run: {res['error']}**", ""])
    c = res["cutoffs"]
    L += [
        f"Score cutoffs: q25={_f(c['q25'], 4)}, q75={_f(c['q75'], 4)}"
        f"{' (DEGENERATE: q25 == q75, no contrast possible)' if c['degenerate'] else ''}",
        "",
    ]
    if c["degenerate"]:
        return "\n".join(L)
    g = res["groups"]
    L += [
        f"HIGH group n={g['high_n']:,}; LOW group n={g['low_n']:,}",
        "",
        "## Results",
        "",
        "| hypothesis | statistic (HIGH vs LOW) | 95% CI | HIGH rate | LOW rate | verdict |",
        "|---|---|---|---|---|---|",
    ]
    devs: list[str] = []
    for key, name in (
        ("H1_fix90", "H1 FIX within 90d (primary)"),
        ("H2_revert90", "H2 REVERT within 90d"),
        ("fix30", "secondary FIX 30d"),
        ("revert30", "secondary REVERT 30d"),
    ):
        r = res[key]
        L.append(
            f"| {name} | MH RR {_f(r['rr_mh'])} | {_ci(r['ci95'])} | "
            f"{_rate(r['exposed'])} | {_rate(r['unexposed'])} | "
            f"{_verdict(r, devs, name)} |"
        )
    h3 = res["H3_ttf"]
    L.append(
        f"| H3 time-to-fix longer for HIGH | Cliff's delta {_f(h3['cliffs_delta'])} | "
        f"{_ci(h3['ci95'])} | median {_f(h3['median_days_high'], 1)} d (n={h3['n_high']}) | "
        f"median {_f(h3['median_days_low'], 1)} d (n={h3['n_low']}) | "
        f"{verdict_delta(h3['ci95'], h3['cliffs_delta'])} |"
    )
    h4 = res["H4_adjusted_or"]
    L.append(
        f"| H4 adjusted OR (size, churn, agent) | OR {_f(h4['or_high'])} | "
        f"{_ci(h4['ci95'])} | | | {verdict_ratio(h4['ci95'], h4['or_high'])} |"
    )
    cu = res["component_U"]
    L.append(
        f"| component: no human review vs reviewed | MH RR {_f(cu['rr_mh'])} | "
        f"{_ci(cu['ci95'])} | {_rate(cu['exposed'])} | {_rate(cu['unexposed'])} | "
        f"{_verdict(cu, devs, 'component')} |"
    )
    L += [
        "",
        f"Spearman(S, FIX90 indicator) over all eligible units: {_f(res['spearman_S_fix90'], 4)}",
        "",
        "## Deviations from the pre-registration",
        "",
        *([f"- {x}" for x in dict.fromkeys(devs)] or ["None recorded by the code."]),
        "",
        "Crude (unstratified) FIX90 risk ratio from the rates above: "
        f"{_f(res['H1_fix90']['exposed']['rate'] / res['H1_fix90']['unexposed']['rate'])}. "
        "The repo-stratified MH estimate is the pre-registered one; the gap between the two "
        "shows how much of the raw association is explained by which repos the PRs sit in.",
        "",
    ]
    return "\n".join(L)


def _fx(x: float, d: int = 3) -> str:
    if x != x:
        return "n/a"
    return "inf" if x == float("inf") else f"{x:.{d}f}"


def render_matched(res: dict[str, Any], manifest: dict[str, Any] | None, command: str) -> str:
    from cdebt.backtest.matched import verdict

    L = [
        "# Matched-pairs backtest results (as measured)",
        "",
        f"Generated by `{command}`. Hypotheses, matching rules and statistics are frozen in "
        "`docs/PREREGISTRATION.md`, committed before this analysis existed. Numbers are copied "
        "from `RESULTS_MATCHED.json`.",
        "",
    ]
    if manifest:
        L.append(f"- Dataset: `{manifest['dataset']}` revision `{manifest['revision']}`")
    L += [
        f"- Merged PRs touching code: {res['prs_total']:,}; eligible (>=90d follow-up): "
        f"{res['eligible_prs']:,}",
        f"- Seed {res['seed']}, bootstrap replicates {res['reps']} (resampling repos)",
        "",
    ]
    if "error" in res:
        return "\n".join(L + [f"**Analysis not run: {res['error']}**", ""])
    L += [
        "## Scope (read first)",
        "",
        "Compares merged agent PRs with NO human review evidence against PRs with substantive "
        "human review, within the same repo, agent, size tercile and +-30 days. Outcome: a "
        "later dataset-visible fix PR touching the same file(s). Review evidence is a weak "
        "proxy for understanding; reviewers may review the PRs they find risky (confounding by "
        "indication); fixes are visible only if they are themselves agent PRs. Association "
        "only.",
        "",
        f"Size tercile edges (additions): {res['size_bin_edges']}",
        "",
        f"U levels among eligible PRs: {json.dumps(res['U_levels_eligible_prs'])}",
        "",
    ]
    L += [
        "## Results",
        "",
        "| run | outcome | pairs (repos) | only UNREV fixed (b) | only REV fixed (c) | "
        "OR b/c [95% CI] | risk diff [95% CI] | rate UNREV / REV | verdict |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for name, r in res["runs"].items():
        for oc in ("fix90", "fix30"):
            s = r[oc]
            if s.get("n_pairs", 0) == 0:
                L.append(f"| {name} | {oc} | 0 | | | | | | no pairs |")
                continue
            L.append(
                f"| {name}{' (PRIMARY)' if name == 'primary_N20' and oc == 'fix90' else ''} | "
                f"{oc} | {s['n_pairs']:,} ({s['n_repos']}) | {s['only_unreviewed_fix_b']} | "
                f"{s['only_reviewed_fix_c']} | {_fx(s['odds_ratio_b_over_c'])} "
                f"[{_fx(s['or_ci95'][0])}, {_fx(s['or_ci95'][1])}] | "
                f"{_fx(s['risk_difference'], 4)} [{_fx(s['rd_ci95'][0], 4)}, "
                f"{_fx(s['rd_ci95'][1], 4)}] | {_fx(s['rate_unreviewed'], 4)} / "
                f"{_fx(s['rate_reviewed'], 4)} | {verdict(s)} |"
            )
    L += [
        "",
        "## Matching bookkeeping and balance",
        "",
        "| run | repos meeting N | UNREV in those repos | REV in those repos | pairs | "
        "mean additions UNREV / REV | median days apart |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, r in res["runs"].items():
        m, b = r["matching"], r["balance"]
        L.append(
            f"| {name} | {m['repos_meeting_threshold']} | {m['unreviewed_in_big_repos']} | "
            f"{m['reviewed_in_big_repos']} | {m['n_pairs']:,} | "
            f"{_fx(b.get('mean_additions_unreviewed', float('nan')), 1)} / "
            f"{_fx(b.get('mean_additions_reviewed', float('nan')), 1)} | "
            f"{_fx(b.get('median_abs_days_apart', float('nan')), 1)} |"
        )
    p = res["runs"]["primary_N20"]["fix90"]
    if p.get("n_pairs"):
        L += [
            "",
            f"Exact McNemar p (primary, NOT corrected for repo clustering, descriptive "
            f"only): {_fx(p['mcnemar_exact_p_unclustered'], 4)}",
        ]
    L += [
        "",
        "## Deviations from the pre-registration",
        "",
        "None recorded by the code. Any deviation (including fixes made after the first run) "
        "must be listed here by the author with the reason.",
        "",
    ]
    return "\n".join(L)
