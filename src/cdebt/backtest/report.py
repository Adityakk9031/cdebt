"""Render RESULTS.md strictly from the measured results dict. No prose is invented."""

from __future__ import annotations

import json
from typing import Any

from cdebt.backtest.analysis import verdict_delta, verdict_ratio


def _f(x: float, d: int = 3) -> str:
    return "n/a" if x != x else f"{x:.{d}f}"


def _ci(c: list[float], d: int = 3) -> str:
    return f"[{_f(c[0], d)}, {_f(c[1], d)}]"


def _rate(r: dict[str, Any]) -> str:
    return f"{r['k']}/{r['n']} = {_f(r['rate'], 4)} (Wilson 95% {_ci(r['ci95'], 4)})"


def render(res: dict[str, Any], manifest: dict[str, Any] | None, command: str) -> str:
    d = res["descriptive"]
    L = [
        "# Backtest results (as measured)",
        "",
        "Generated by `" + command + "`. Definitions and hypotheses were frozen in "
        "`docs/METHOD.md` (pre-registration) before this run. Numbers below are copied from "
        "`RESULTS.json`; nothing is hand-edited.",
        "",
    ]
    if manifest:
        L += [
            f"- Dataset: `{manifest['dataset']}` revision `{manifest['revision']}`, fetched "
            f"{manifest['fetched_at']}"
        ]
    L += [
        f"- Merged PRs: {d['merged_prs']:,}; (PR, file) units: {d['units']:,}; eligible "
        f"(>=90d follow-up): {d['eligible_units']:,} in {d['eligible_repos']:,} repos",
        f"- Seed {res['seed']}, bootstrap replicates {res['reps']} (resampling repos)",
        "",
        "## Scope of this test (read first)",
        "",
        "Tests the **proxy** `S = (1-U)(1+C)` only. `ai_share` is constant (all PRs are "
        "agent-authored) and `blast_radius` is not tested. Outcomes are observable only when "
        "the follow-up is itself an agent PR in the curated set, so counts are undercounted "
        "and repo-activity confounded (analysis is stratified by repo). The quiz itself is "
        "not evaluated. Association only; no causal claim.",
        "",
        "## Descriptives",
        "",
        "| outcome (eligible units) | rate |",
        "|---|---|",
    ]
    for k, r in d["base_rates_eligible"].items():
        L.append(f"| {k} | {_rate(r)} |")
    L += [
        "",
        f"U levels (eligible units): {json.dumps(d['U_levels'])}",
        "",
        f"Agents (eligible units): {json.dumps(d['agents'])}",
        "",
    ]
    if "error" in res:
        return "\n".join(L + [f"**Analysis not run: {res['error']}**", ""])
    c = res["cutoffs"]
    L += [
        f"Score cutoffs: q25={_f(c['q25'], 4)}, q75={_f(c['q75'], 4)}"
        f"{' (DEGENERATE: q25 == q75, no contrast possible)' if c['degenerate'] else ''}",
        "",
    ]
    if c["degenerate"]:
        return "\n".join(L)
    g = res["groups"]
    L += [
        f"HIGH group n={g['high_n']:,}; LOW group n={g['low_n']:,}",
        "",
        "## Results",
        "",
        "| hypothesis | statistic (HIGH vs LOW) | 95% CI | HIGH rate | LOW rate | verdict |",
        "|---|---|---|---|---|---|",
    ]
    for key, name in (
        ("H1_fix90", "H1 FIX within 90d (primary)"),
        ("H2_revert90", "H2 REVERT within 90d"),
        ("fix30", "secondary FIX 30d"),
        ("revert30", "secondary REVERT 30d"),
    ):
        r = res[key]
        L.append(
            f"| {name} | MH RR {_f(r['rr_mh'])} | {_ci(r['ci95'])} | "
            f"{_rate(r['exposed'])} | {_rate(r['unexposed'])} | "
            f"{verdict_ratio(r['ci95'], r['rr_mh'])} |"
        )
    h3 = res["H3_ttf"]
    L.append(
        f"| H3 time-to-fix longer for HIGH | Cliff's delta {_f(h3['cliffs_delta'])} | "
        f"{_ci(h3['ci95'])} | median {_f(h3['median_days_high'], 1)} d (n={h3['n_high']}) | "
        f"median {_f(h3['median_days_low'], 1)} d (n={h3['n_low']}) | "
        f"{verdict_delta(h3['ci95'], h3['cliffs_delta'])} |"
    )
    h4 = res["H4_adjusted_or"]
    L.append(
        f"| H4 adjusted OR (size, churn, agent) | OR {_f(h4['or_high'])} | "
        f"{_ci(h4['ci95'])} | | | {verdict_ratio(h4['ci95'], h4['or_high'])} |"
    )
    cu = res["component_U"]
    L.append(
        f"| component: no human review vs reviewed | MH RR {_f(cu['rr_mh'])} | "
        f"{_ci(cu['ci95'])} | {_rate(cu['exposed'])} | {_rate(cu['unexposed'])} | "
        f"{verdict_ratio(cu['ci95'], cu['rr_mh'])} |"
    )
    L += [
        "",
        f"Spearman(S, FIX90 indicator) over all eligible units: {_f(res['spearman_S_fix90'], 4)}",
        "",
        "## Deviations from the pre-registration",
        "",
        "None recorded by the code. Any manual deviation must be listed here by the author.",
        "",
    ]
    return "\n".join(L)
