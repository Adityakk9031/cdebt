"""The local pre-push flow: where the quiz happens, before the PR exists.

`cdebt init` installs a git pre-push hook (with consent). On `git push` the hook finds AI-written
changed lines that nobody has understood, runs the adaptive quiz on the developer's terminal,
writes hash-bound records to `refs/notes/cdebt`, and pushes the notes BEFORE the branch. It never
blocks the push: with no terminal (an agent pushing on its own) it prints a notice and exits 0, and
`git push --no-verify` always bypasses it. CI (the Action) is what stops a merge.
"""

from __future__ import annotations

import contextlib
import os
import shlex
import shutil
import stat
import sys
from collections.abc import Callable, Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import IO

from cdebt import gitutil, notes
from cdebt.agents import userconfig
from cdebt.config import Config
from cdebt.models import Probe, Violation

ZERO = "0" * 40
BEGIN = "# >>> cdebt pre-push >>>"
END = "# <<< cdebt pre-push <<<"
NOTICE_NO_TTY = (
    "cdebt: AI-written code in this push has not been understood by a human yet. No terminal is "
    "attached, so no quiz was run. The PR check will show this code as NOT UNDERSTOOD until a "
    "human runs `cdebt quiz --pr <number>`."
)


def hook_block(cdebt_exe: str | None) -> str:
    fallback = (
        f"elif [ -x {shlex.quote(cdebt_exe)} ]; then CDEBT={shlex.quote(cdebt_exe)}\n"
        if cdebt_exe
        else ""
    )
    return (
        f"{BEGIN}\n"
        "# installed by `cdebt init`. Skip with: git push --no-verify. Never blocks a push.\n"
        'if [ -z "$CDEBT_IN_HOOK" ]; then\n'
        "  if command -v cdebt >/dev/null 2>&1; then CDEBT=cdebt\n"
        f"  {fallback}"
        '  else CDEBT=""; echo "cdebt: not installed, skipping the pre-push check" >&2\n'
        "  fi\n"
        '  [ -n "$CDEBT" ] && "$CDEBT" hook pre-push "$@" || true\n'
        "fi\n"
        f"{END}\n"
    )


def hooks_dir(repo: Path) -> Path:
    """Where git will look for hooks (honours core.hooksPath)."""
    out = gitutil.run(["rev-parse", "--git-path", "hooks"], repo).strip()
    p = Path(out)
    return p if p.is_absolute() else (repo / p)


@dataclass
class InstallPlan:
    path: Path
    action: str  # create | append | already | manual
    message: str
    content: str = ""


def plan_install(repo: Path, cdebt_exe: str | None = None) -> InstallPlan:
    """What `cdebt init` would do to the pre-push hook. Never overwrites an existing hook."""
    d = hooks_dir(repo)
    hp = d / "pre-push"
    block = hook_block(cdebt_exe or shutil.which("cdebt"))
    if d.name == "_" and d.parent.name == ".husky":  # husky: the user-owned script is one up
        hp = d.parent / "pre-push"
    if not hp.exists():
        return InstallPlan(hp, "create", f"create {hp}", "#!/bin/sh\n" + block)
    text = hp.read_text(errors="replace")
    if BEGIN in text:
        return InstallPlan(hp, "already", f"{hp} already has the cdebt block")
    if "pre-commit" in text and "File generated by pre-commit" in text:
        return InstallPlan(
            hp,
            "manual",
            "this hook is managed by the pre-commit framework; add to .pre-commit-config.yaml:\n"
            "  - repo: local\n    hooks:\n      - id: cdebt\n        name: cdebt\n"
            "        entry: cdebt hook pre-push\n        language: system\n"
            "        stages: [pre-push]\n        always_run: true\n        pass_filenames: false",
        )
    first = text.splitlines()[0] if text else ""
    if not first.startswith("#!") or not any(s in first for s in ("sh", "bash", "zsh")):
        return InstallPlan(
            hp,
            "manual",
            f"{hp} is not a shell script; add a call to `cdebt hook pre-push` yourself",
        )
    return InstallPlan(hp, "append", f"append a marked cdebt block to the end of {hp}", block)


def apply_install(plan: InstallPlan) -> None:
    if plan.action == "create":
        plan.path.parent.mkdir(parents=True, exist_ok=True)
        plan.path.write_text(plan.content)
        plan.path.chmod(plan.path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    elif plan.action == "append":
        with open(plan.path, "a") as f:
            f.write("\n" + plan.content)


# ---- working out what is being pushed ----


@dataclass
class Push:
    local_ref: str
    local_sha: str
    remote_ref: str
    remote_sha: str


def parse_refs(stdin_text: str) -> list[Push]:
    out: list[Push] = []
    for ln in stdin_text.splitlines():
        parts = ln.split()
        if len(parts) == 4:
            out.append(Push(*parts))
    return out


def default_base(repo: Path, remote: str) -> str | None:
    for cand in (f"{remote}/HEAD", f"{remote}/main", f"{remote}/master"):
        with contextlib.suppress(gitutil.GitError):
            gitutil.resolve(repo, cand)
            return cand
    return None


def base_for(repo: Path, remote: str, p: Push) -> str | None:
    if p.remote_sha != ZERO:
        with contextlib.suppress(gitutil.GitError):
            return gitutil.resolve(repo, p.remote_sha)
    db = default_base(repo, remote)
    if db is None:
        return None
    with contextlib.suppress(gitutil.GitError):
        return gitutil.run(["merge-base", p.local_sha, db], repo).strip()
    return None


# ---- the terminal ----


@contextlib.contextmanager
def terminal() -> Iterator[IO[str] | None]:
    """The developer's terminal, even though a hook's stdin carries the ref list. CDEBT_TTY points
    at a file for tests. None when no terminal is attached (an agent pushing by itself)."""
    override = os.environ.get("CDEBT_TTY")
    f: IO[str] | None = None
    try:
        f = open(override or "/dev/tty")  # noqa: SIM115 - closed below
    except OSError:
        f = None
    try:
        yield f
    finally:
        if f is not None:
            f.close()


@dataclass
class QuizSummary:
    cleared: int = 0
    not_cleared: int = 0
    skipped: list[str] = field(default_factory=list)
    wrote_notes: bool = False


def violations_to_quiz(repo: Path, cfg: Config, base: str, head: str) -> list[Violation]:
    from cdebt.gate import run_gate

    res = run_gate(repo, cfg, base, head, use_notes=True)
    return [v for v in res.violations if v.status != "attested" or not v.symbol.startswith("<")]


def quiz_changes(
    repo: Path, cfg: Config, base: str, head: str, say: Callable[[str], None]
) -> QuizSummary:
    """Quiz every AI-written, not-understood function in base..head (working tree == head).
    Writes records to a note on `head`; returns a summary. The caller pushes the notes."""
    from cdebt import adaptive
    from cdebt.probes.base import LETTERS
    from cdebt.quiz import build_quiz, dirty

    out = QuizSummary()
    found = violations_to_quiz(repo, cfg, base, head)
    vs = [v for v in found if not v.symbol.startswith("<")]
    module_level = sorted({v.path for v in found if v.symbol.startswith("<")})
    if not vs:
        for f in module_level:
            out.skipped.append(f"{f}: module-level code can only be attested (`cdebt attest`)")
        return out
    by_file: dict[str, set[str]] = {}
    for v in vs:
        by_file.setdefault(v.path, set()).add(v.symbol)
    policy = adaptive.load_policy(repo)
    choice = userconfig.load()
    sink = notes.NotesSink(repo, head)
    n = {"q": 0}

    def ask(p: Probe, timeout: float | None) -> tuple[str | None, float]:
        n["q"] += 1
        tag = f" (follow-up, {timeout:.0f} s)" if timeout is not None else ""
        say(f"\nQ{n['q']} [{p.difficulty}] {p.question}{tag}")
        for j, o in enumerate(p.options):
            say(f"  {LETTERS[j]}) {o}")
        return adaptive.tty_ask(p, timeout)

    for rel, syms in sorted(by_file.items()):
        if dirty(repo, rel):
            out.skipped.append(f"{rel}: differs from HEAD; commit it first")
            continue
        probes, units, skips = build_quiz(
            repo, rel, cfg, n=12, per_unit=6, agent=choice, store=None
        )
        probes = [p for p in probes if p.symbol in syms]
        out.skipped += [s for s in skips if "agent" in s.lower()]
        quizzable = {p.symbol for p in probes}
        for s in sorted(syms - quizzable):
            out.skipped.append(f"{rel}::{s}: no question can be verified by execution here")
        if not probes:
            continue
        source = (repo / rel).read_text()
        outcomes = adaptive.run_adaptive(repo, rel, cfg, units, source, probes, ask, policy)
        adaptive.record_outcomes(rel, units, outcomes, store=sink)  # type: ignore[arg-type]
        for o in outcomes:
            say(
                f"{rel}::{o.symbol}: {'UNDERSTOOD' if o.cleared else 'NOT UNDERSTOOD'} ({o.reason})"
            )
            out.cleared += 1 if o.cleared else 0
            out.not_cleared += 0 if o.cleared else 1
    sink.save()
    out.wrote_notes = out.cleared + out.not_cleared > 0
    return out


def run_pre_push(repo: Path, remote: str, stdin_text: str, say: Callable[[str], None]) -> int:
    """Entry point for `cdebt hook pre-push`. Always returns 0: it never blocks a push."""
    if os.environ.get("CDEBT_IN_HOOK"):
        return 0
    from cdebt.config import load_config

    cfg = load_config(repo)
    try:
        head = gitutil.resolve(repo, "HEAD")
        pushes = [
            p
            for p in parse_refs(stdin_text)
            if p.local_sha != ZERO and not p.local_ref.startswith(("refs/notes/", "refs/tags/"))
        ]
        if not pushes:  # no refs on stdin (an earlier hook consumed it): use HEAD vs default base
            db = default_base(repo, remote)
            pushes = [Push("HEAD", head, "", ZERO)] if db else []
        todo: list[tuple[str, str]] = []
        for p in pushes:
            if p.local_sha != head:
                say(f"cdebt: {p.local_ref} is not the checked-out commit; skipping the quiz for it")
                continue
            base = base_for(repo, remote, p)
            if base is None:
                say("cdebt: cannot find a base branch to compare with; skipping the check")
                continue
            if violations_to_quiz(repo, cfg, base, p.local_sha):
                todo.append((base, p.local_sha))
        if not todo:
            return 0
        with terminal() as tty:
            if tty is None:
                say(NOTICE_NO_TTY)
                return 0
            from cdebt import sandbox

            sandbox.set_default_isolation("host" if sandbox.is_trusted() else "strong")
            old_stdin = sys.stdin
            sys.stdin = tty
            try:
                total = QuizSummary()
                for base, sha in todo:
                    s = quiz_changes(repo, cfg, base, sha, say)
                    total.cleared += s.cleared
                    total.not_cleared += s.not_cleared
                    total.skipped += s.skipped
                    total.wrote_notes = total.wrote_notes or s.wrote_notes
            finally:
                sys.stdin = old_stdin
        for line in total.skipped:
            say(f"cdebt: {line}")
        if total.wrote_notes:
            ok, msg = notes.push_notes(repo, remote)
            say(
                "cdebt: notes pushed before the branch"
                if ok
                else f"cdebt: could not push notes ({msg}); the PR check may show NOT UNDERSTOOD"
            )
    except (gitutil.GitError, sandbox_error()) as e:
        say(f"cdebt: skipped the pre-push check ({e})")
    return 0


def sandbox_error() -> type[Exception]:
    from cdebt.sandbox import SandboxUnavailable

    return SandboxUnavailable
